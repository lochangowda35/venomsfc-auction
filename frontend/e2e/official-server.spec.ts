import { expect, test } from '@playwright/test'

test('official PostgreSQL instance: branding, fixed teams, protected TV popup and shared logout', async ({ page, context, baseURL }) => {
  test.skip(process.env.AUCTION_E2E_OFFICIAL !== '1' || !process.env.AUCTION_E2E_PASSWORD,
    'Requires an explicitly prepared disposable official-team server.')
  test.setTimeout(90000)
  const url = new URL(baseURL!)
  expect(['127.0.0.1', 'localhost']).toContain(url.hostname)
  expect(url.port).not.toBe('5000')
  const initial = await (await context.request.get('/api/auction/state')).json()
  expect(initial.fixed_teams).toBe(true)
  expect(initial.status).toBe('setup')
  expect(initial.players).toHaveLength(0)
  expect(initial.teams.map((team: { name: string }) => team.name)).toEqual([
    'BlackMambas', 'Cobras', 'Vipers', 'Pythons', 'Anacondas',
  ])
  for (const name of ['venoms-fc', 'auction-banner', 'blackmambas', 'cobras', 'vipers', 'pythons', 'anacondas']) {
    const response = await context.request.get(`/api/branding/${name}.jpg`)
    expect(response.ok()).toBe(true)
    expect(response.headers()['content-type']).toContain('image/jpeg')
    expect((await response.body()).length).toBeGreaterThan(1000)
  }
  await page.goto('/')
  await expect(page.locator('.team-card')).toHaveCount(5)
  await expect(page.getByRole('link', { name: 'TV display', exact: true })).toHaveCount(0)
  expect(await page.locator('.official-banner img').evaluate((image: HTMLImageElement) =>
    image.complete && image.naturalWidth > 1000)).toBe(true)
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/display')
  await expect(page).toHaveURL(/\/host\?next=display$/)
  await expect(page.getByLabel('Host password')).toBeVisible()
  await expect(page.locator('.stage, .team-card, .host-controls')).toHaveCount(0)
  expect((await context.request.get('/api/auction/display-state')).status()).toBe(401)
  await page.getByLabel('Host password').fill(process.env.AUCTION_E2E_PASSWORD!)
  await page.getByRole('button', { name: /Unlock TV display/ }).click()
  await expect(page).toHaveURL(/\/display$/)
  await expect(page.locator('.team-card')).toHaveCount(5)
  await expect(page.locator('.host-controls')).toHaveCount(0)
  const desk = await context.newPage()
  await desk.goto('/host')
  await expect(desk.locator('.setup-team')).toHaveCount(5)
  await expect(desk.locator('.setup-team button')).toHaveCount(0)
  await expect(desk.getByRole('button', { name: /Add team/ })).toHaveCount(0)
  await expect(desk.getByRole('button', { name: /Add player/ })).toBeEnabled()
  const popupEvent = desk.waitForEvent('popup')
  await desk.getByRole('button', { name: /Open TV display/ }).click()
  const tv = await popupEvent
  await expect(tv).toHaveURL(/\/display$/)
  await expect(tv.locator('.team-card')).toHaveCount(5)
  await expect(tv.locator('.host-controls')).toHaveCount(0)
  const spectator = await context.newPage()
  await spectator.goto('/')
  await expect(spectator.locator('.team-card')).toHaveCount(5)
  await expect(spectator.locator('.setup-launch, .host-controls')).toHaveCount(0)
  await desk.locator('.view-switch summary').click()
  await desk.getByRole('button', { name: 'Sign out', exact: true }).click()
  for (const privatePage of [desk, page, tv]) {
    await privatePage.bringToFront()
    await expect(privatePage.getByLabel('Host password')).toBeVisible({ timeout: 15000 })
    await expect(privatePage.locator('.team-card, .setup-team, .host-controls')).toHaveCount(0)
  }
  await expect(spectator.locator('.team-card')).toHaveCount(5)
  expect((await context.request.get('/api/auction/display-state')).status()).toBe(401)
  await tv.close()
  await desk.close()
  await spectator.close()
})
